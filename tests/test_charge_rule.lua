local root=arg[1]
local events={}
local rule=dofile(root..'/tools/next_attacks/charge.lua').new(function(s)events[#events+1]=s end)
local function sample(t,d,changes)
    local s={key='mission/actor/unit',cycle=1,charging=true,alive=true,time=t,distance=d,range=5,
        target=100,local_entity=100,target_verified=true,enabled=true}
    for k,v in pairs(changes or{})do s[k]=v end
    return rule:observe(s)
end
assert(sample(0,9)=='outside_or_no_entry')
assert(sample(.1,5)=='trigger'and #events==1)
assert(sample(.2,4)=='entry_already_consumed')
assert(sample(.3,8)=='entry_already_consumed')
assert(sample(.4,4)=='entry_already_consumed'and #events==1)
assert(sample(.5,4,{charging=false})=='not_charging'and rule.count==0)
assert(sample(.6,4,{cycle=2,started=true})=='trigger'and #events==2)
rule:reset()
assert(sample(0,4)=='entry_already_consumed','joining inside is not a fresh entry')
assert(sample(.1,8)=='entry_already_consumed')
assert(sample(.2,4)=='entry_already_consumed')
rule:reset()
sample(0,8)
assert(sample(.1,4,{target=101})=='other_target')
assert(sample(.2,4)=='entry_already_consumed','retargeting inside cannot manufacture entry')
rule:reset();sample(0,8)
assert(sample(.1,4,{target_verified=false})=='target_unconfirmed')
assert(sample(.2,4)=='entry_already_consumed')
rule:reset();sample(0,8)
assert(sample(.5,4)=='continuity_unconfirmed')
assert(sample(.6,8)=='continuity_unconfirmed')
assert(sample(.7,4)=='continuity_unconfirmed')
rule:reset();sample(0,8)
assert(sample(.1,6,{range=10})=='continuity_unconfirmed','changing range is not entry')
rule:reset()
assert(sample(0,0,{range=0})=='range_disabled')
assert(sample(.1,4,{range=5})=='continuity_unconfirmed')
rule:reset();sample(0,8)
assert(sample(.1,4,{enabled=false})=='move_disabled')
assert(sample(.2,4)=='entry_already_consumed')
assert(sample(.3,4,{cycle=2,started=true})=='trigger')
assert(sample(.4,4,{alive=false})=='not_charging')
assert(sample(.5,4,{cycle=3,started=true})=='trigger')
assert(sample(.6,0/0)=='invalid_input')
assert(sample(.6,4,{range=16})=='invalid_input')
assert(sample(.6,4,{range=.5})=='invalid_input')
assert(sample(.6,4,{cycle={}})=='invalid_input')
assert(sample(.6,4,{key=''})=='invalid_input')
rule:reset();sample(0,8)
assert(sample(.1,4,{target='100'})=='target_unconfirmed')
rule:reset()
for i=1,128 do assert(sample(0,8,{key='actor'..i})=='outside_or_no_entry')end
assert(sample(0,8,{key='overflow'})=='state_limit'and rule.count==128)
rule:finish('actor1')
assert(sample(0,8,{key='overflow'})=='outside_or_no_entry'and rule.count==128)
rule:reset()
assert(sample(0,20,{key='charger',range=15})=='outside_or_no_entry')
assert(sample(0,20,{key='commander',range=5})=='outside_or_no_entry')
assert(sample(.1,15,{key='charger',range=15})=='trigger','inclusive 15m maximum is accepted')
assert(sample(.1,15,{key='commander',range=5})=='outside_or_no_entry','commander keeps its independent 5m threshold')
assert(sample(.2,4,{key='commander',range=5})=='trigger')
assert(sample(.2,14,{key='charger',range=14})=='continuity_unconfirmed')
assert(sample(.3,4,{key='commander',range=5})=='entry_already_consumed','editing charger range cannot invalidate commander state')
print('PASS charge entry logic: local lock, first crossing only, baseline/retarget/gap/range-edit rejection, independent 0-15m thresholds, zero disables, independent cycles and bounded state; live adapter still pending')
